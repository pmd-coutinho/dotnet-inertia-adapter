using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace InertiaNet.Pathfinder.Generation;

/// <summary>Commits staged files without deleting user files or rewriting unchanged modules.</summary>
internal static class GeneratedOutput
{
    public const string ManifestName = ".pathfinder-manifest.json";
    public const string FileListName = ".pathfinder-files";
    public const string StampName = ".pathfinder.stamp";
    public const string InputFileListName = ".pathfinder-inputs";
    public const string Header = "// Generated by InertiaNet.Pathfinder. Do not edit.\n";
    private const string LockName = ".pathfinder.lock";
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
    private sealed record Manifest(int Version, SortedDictionary<string, string> Files);
    private sealed record Backup(byte[]? Content, DateTime LastWrite);

    public static bool Synchronize(string stagedDirectory, PathfinderConfig config, Action<string>? beforeWrite = null)
    {
        var root = PhysicalDirectory(Path.GetFullPath(config.OutputPath));
        var source = Path.GetFullPath(config.ProjectPath);
        source = PhysicalDirectory(File.Exists(source) ? Path.GetDirectoryName(source)! : source);
        if (IsWithin(root, source))
            throw new InvalidOperationException("The output directory cannot be the project directory or its ancestor.");

        var staged = new SortedDictionary<string, byte[]>(StringComparer.Ordinal);
        foreach (var path in Directory.EnumerateFiles(stagedDirectory, "*", SearchOption.AllDirectories))
        {
            var relative = Path.GetRelativePath(stagedDirectory, path).Replace('\\', '/');
            var content = File.ReadAllText(path).Replace("\r\n", "\n");
            staged.Add(relative, Encoding.UTF8.GetBytes(path.EndsWith(".ts", StringComparison.Ordinal) ? Header + content : content));
        }
        staged[InputFileListName] = Encoding.UTF8.GetBytes(string.Join('\n', config.InputFiles.Select(file => Path.GetRelativePath(source, file).Replace('\\', '/'))
            .Distinct(StringComparer.Ordinal).OrderBy(file => file, StringComparer.Ordinal)) + "\n");
        if (config.Check) return Apply(root, staged, config, null, dryRun: true);
        Directory.CreateDirectory(root);
        // A concurrent build may generate the same directory for several target
        // frameworks. Serialize commits and read ownership only after acquiring it.
        using var outputLock = AcquireLock(root);
        return Apply(root, staged, config, beforeWrite, dryRun: false);
    }

    private static FileStream AcquireLock(string root)
    {
        var lockPath = Target(root, LockName, control: true);
        var deadline = DateTime.UtcNow.AddSeconds(10);
        while (true)
        {
            try { return new FileStream(lockPath, FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None, 1, FileOptions.DeleteOnClose); }
            catch (IOException) when (DateTime.UtcNow < deadline) { Thread.Sleep(50); }
        }
    }

    private static bool Apply(string root, SortedDictionary<string, byte[]> staged, PathfinderConfig config,
        Action<string>? beforeWrite, bool dryRun)
    {
        var manifestPath = Target(root, ManifestName, control: true);
        Manifest previous;
        try
        {
            previous = File.Exists(manifestPath)
                ? JsonSerializer.Deserialize<Manifest>(File.ReadAllBytes(manifestPath), JsonOptions)
                    ?? throw new JsonException("Empty manifest.")
                : new(1, new(StringComparer.Ordinal));
        }
        catch (JsonException ex) { throw new InvalidOperationException("The generated-file manifest is invalid. Restore it or choose a fresh output directory.", ex); }
        if (previous.Version != 1 || previous.Files is null)
            throw new InvalidOperationException("Unsupported generated-file manifest version.");
        foreach (var path in previous.Files.Keys) _ = Target(root, path, control: path == InputFileListName);
        foreach (var path in staged.Keys)
        {
            var target = Target(root, path, control: path == InputFileListName);
            if (File.Exists(target) && !previous.Files.ContainsKey(path) && !config.Adopt
                && path != InputFileListName
                && !File.ReadAllText(target).StartsWith(Header, StringComparison.Ordinal))
                throw new InvalidOperationException($"Refusing to overwrite unowned file '{target}'. Use a fresh output directory, or --adopt to adopt matching legacy generated paths.");
        }
        var owned = new SortedDictionary<string, string>(StringComparer.Ordinal);
        if (!config.Clean)
            foreach (var (path, hash) in previous.Files)
                if (File.Exists(Target(root, path, control: path == InputFileListName))) owned[path] = hash;
        foreach (var (path, content) in staged) owned[path] = Convert.ToHexString(SHA256.HashData(content)).ToLowerInvariant();
        var deleted = config.Clean ? previous.Files.Keys.Except(staged.Keys, StringComparer.Ordinal).Where(path => File.Exists(Target(root, path))).ToArray() : [];
        var desired = new SortedDictionary<string, byte[]>(staged, StringComparer.Ordinal)
        {
            [ManifestName] = Encoding.UTF8.GetBytes(JsonSerializer.Serialize(new Manifest(1, owned), JsonOptions) + "\n"),
            [FileListName] = Encoding.UTF8.GetBytes(string.Join('\n', owned.Keys) + "\n"),
        };
        var changed = desired.Where(pair => !File.Exists(Target(root, pair.Key, control: true))
                || !File.ReadAllBytes(Target(root, pair.Key, control: true)).AsSpan().SequenceEqual(pair.Value))
            .ToArray();
        if (dryRun) return changed.Length > 0 || deleted.Length > 0;

        var backups = new Dictionary<string, Backup>(StringComparer.Ordinal);
        try
        {
            foreach (var (relative, content) in changed)
            {
                var path = Target(root, relative, control: true);
                BackupFile(path, backups);
                beforeWrite?.Invoke(relative);
                AtomicWrite(path, content);
            }
            foreach (var relative in deleted)
            {
                var path = Target(root, relative);
                BackupFile(path, backups);
                beforeWrite?.Invoke(relative);
                File.Delete(path);
            }
            var stamp = Target(root, StampName, control: true);
            BackupFile(stamp, backups);
            if (!File.Exists(stamp)) AtomicWrite(stamp, []);
            File.SetLastWriteTimeUtc(stamp, DateTime.UtcNow);
        }
        catch
        {
            foreach (var (path, backup) in backups.Reverse())
            {
                if (backup.Content is null) File.Delete(path);
                else { AtomicWrite(path, backup.Content); File.SetLastWriteTimeUtc(path, backup.LastWrite); }
            }
            throw;
        }
        return changed.Length > 0 || deleted.Length > 0;
    }

    private static void BackupFile(string path, Dictionary<string, Backup> backups)
        => backups.TryAdd(path, File.Exists(path) ? new(File.ReadAllBytes(path), File.GetLastWriteTimeUtc(path)) : new(null, default));

    private static void AtomicWrite(string path, byte[] content)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temporary = path + ".tmp-" + Guid.NewGuid().ToString("N");
        try { File.WriteAllBytes(temporary, content); File.Move(temporary, path, overwrite: true); }
        finally { File.Delete(temporary); }
    }

    private static string Target(string root, string relative, bool control = false)
    {
        if (string.IsNullOrWhiteSpace(relative) || Path.IsPathRooted(relative) || relative.Contains('\\')
            || relative.Split('/').Any(part => part is "" or "." or "..")
            || (!control && relative.StartsWith(".pathfinder", StringComparison.Ordinal)))
            throw new InvalidOperationException($"Invalid generated-file path '{relative}'.");
        var path = Path.GetFullPath(Path.Combine(root, relative));
        if (!IsWithin(root, path) || path == root) throw new InvalidOperationException($"Generated path escapes its output directory: '{relative}'.");
        var current = root;
        foreach (var part in relative.Split('/'))
        {
            current = Path.Combine(current, part);
            if (new FileInfo(current).LinkTarget is not null || new DirectoryInfo(current).LinkTarget is not null)
                throw new InvalidOperationException($"Generated output cannot traverse a symbolic link: '{current}'.");
        }
        if (Directory.Exists(path)) throw new InvalidOperationException($"A directory conflicts with generated file '{path}'.");
        return path;
    }

    private static string PhysicalDirectory(string path)
    {
        var parent = Path.GetDirectoryName(path);
        if (string.IsNullOrEmpty(parent) || parent == path) return path;
        var directory = new DirectoryInfo(path);
        if (directory.LinkTarget is not null)
            return PhysicalDirectory(directory.ResolveLinkTarget(returnFinalTarget: true)!.FullName);
        return Path.Combine(PhysicalDirectory(parent), Path.GetFileName(path));
    }

    private static bool IsWithin(string parent, string path)
        => path.Equals(parent, OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal)
            || path.StartsWith(Path.EndsInDirectorySeparator(parent) ? parent : parent + Path.DirectorySeparatorChar,
                OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal);

    public static string PathUnder(string root, params string[] segments)
    {
        var path = Path.GetFullPath(Path.Combine([root, ..segments]));
        if (path == root || !IsWithin(Path.GetFullPath(root), path))
            throw new InvalidOperationException($"Generated path '{path}' escapes its staging directory.");
        return path;
    }
}
